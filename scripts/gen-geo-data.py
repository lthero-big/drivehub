#!/usr/bin/env python3
"""Generate web/src/lib/geo-data.ts — the offline world map used by the stats page (DEPTAI-485 r6 #4).

Inputs (downloaded into a cache dir, default /tmp/geo):
  world-atlas@2.0.2 land-110m.json / countries-110m.json  (Natural Earth, public domain; package ISC)
  i18n-iso-countries@7.14 codes.json + langs/zh.json      (MIT)
Output: LAND_PATH (equirectangular, x = lon+180, y = 90-lat, cropped at 58°S) and
        COUNTRIES {alpha2: [lon, lat, 中文名]} (label point = centroid of the largest polygon).
usage: scripts/gen-geo-data.py [cache_dir]
"""
import json, os, sys, urllib.request

CACHE = sys.argv[1] if len(sys.argv) > 1 else "/tmp/geo"
SRC = {
    "land-110m.json": "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json",
    "countries-110m.json": "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json",
    "codes.json": "https://cdn.jsdelivr.net/npm/i18n-iso-countries@7.14.0/codes.json",
    "zh.json": "https://cdn.jsdelivr.net/npm/i18n-iso-countries@7.14.0/langs/zh.json",
}
os.makedirs(CACHE, exist_ok=True)
for f, u in SRC.items():
    p = os.path.join(CACHE, f)
    if not os.path.exists(p):
        urllib.request.urlretrieve(u, p)
load = lambda f: json.load(open(os.path.join(CACHE, f), encoding="utf-8"))

def decoder(topo):
    sx, sy = topo["transform"]["scale"]; tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0; pts = []
        for dx, dy in arc:
            x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    def ring(idx):
        out = []
        for i in idx:
            pts = arcs[i] if i >= 0 else arcs[~i][::-1]
            out.extend(pts if not out else pts[1:])
        return out
    def polys(g):
        if g["type"] == "Polygon": return [[ring(r) for r in g["arcs"]]]
        if g["type"] == "MultiPolygon": return [[ring(r) for r in p] for p in g["arcs"]]
        return []
    return polys

MIN_LAT = -58
def path(rings):
    out = []
    for r in rings:
        if max(lat for _, lat in r) < MIN_LAT: continue
        seg = []; prev = None
        for lon, lat in r:
            x, y = round(lon + 180, 1), round(90 - max(lat, MIN_LAT), 1)
            if prev and (x, y) == prev: continue
            # never draw across the antimeridian
            cmd = "M" if not seg or (prev and abs(x - prev[0]) > 180) else "L"
            seg.append(f"{cmd}{x:g},{y:g}"); prev = (x, y)
        if len(seg) > 2: out.append("".join(seg) + "Z")
    return "".join(out)

def area_centroid(r):
    a = cx = cy = 0.0
    for (x0, y0), (x1, y1) in zip(r, r[1:] + r[:1]):
        f = x0 * y1 - x1 * y0; a += f; cx += (x0 + x1) * f; cy += (y0 + y1) * f
    if abs(a) < 1e-12: return 0, r[0]
    return abs(a / 2), (cx / (3 * a), cy / (3 * a))

land = load("land-110m.json"); lpolys = decoder(land)
LAND = path([r for g in land["objects"]["land"]["geometries"] for p in lpolys(g) for r in p[:1]])

ctry = load("countries-110m.json"); cpolys = decoder(ctry)
num2a2 = {c[2]: c[0] for c in load("codes.json")}
zh = load("zh.json")["countries"]
name = lambda a2: (zh[a2] if isinstance(zh[a2], str) else zh[a2][0]) if a2 in zh else a2
# hand-placed label points where the largest-polygon centroid is misleading (overseas parts / antimeridian)
OVERRIDE = {"US": (-98.5, 39.5), "FR": (2.5, 46.6), "NO": (9.5, 61.5), "RU": (90, 61), "FJ": (178, -17.8),
            "CN": (104, 35), "CA": (-101, 57), "NZ": (172.5, -41.5), "GB": (-2, 53), "NL": (5.3, 52.2), "KI": (173, 1.4)}
EXTRA = {"SG": (103.8, 1.35), "HK": (114.2, 22.3), "MO": (113.55, 22.2), "TW": (121, 23.7)}
countries = {}
for g in ctry["objects"]["countries"]["geometries"]:
    a2 = num2a2.get(str(g.get("id", "")).zfill(3))
    if not a2: continue
    if a2 in OVERRIDE: lon, lat = OVERRIDE[a2]
    else:
        best = max((area_centroid(p[0]) for p in cpolys(g)), key=lambda t: t[0], default=None)
        if not best: continue
        lon, lat = best[1]
    countries[a2] = [round(lon, 1), round(lat, 1), name(a2)]
for a2, (lon, lat) in EXTRA.items():
    countries.setdefault(a2, [lon, lat, name(a2)])
countries["TW"][2] = "中国台湾"; countries["HK"][2] = "中国香港"; countries["MO"][2] = "中国澳门"

out = os.path.join(os.path.dirname(__file__), "..", "web", "src", "lib", "geo-data.ts")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/gen-geo-data.py (DEPTAI-485 r6 #4) — do not edit by hand.\n")
    f.write("// Land outline: world-atlas 2.0.2 land-110m (Natural Earth, public domain; package ISC), equirectangular,\n")
    f.write("// x = lon + 180, y = 90 - lat, cropped at 58°S. Country label points + Chinese names: world-atlas\n")
    f.write("// countries-110m + i18n-iso-countries 7.14 (MIT).\n")
    f.write(f"export const LAND_PATH = {json.dumps(LAND)};\n")
    f.write(f"export const COUNTRIES: Record<string, [number, number, string]> = {json.dumps(countries, ensure_ascii=False, separators=(',', ':'))};\n")
print(f"wrote {out}: land {len(LAND)} chars, {len(countries)} countries")
